/**
 * Build-time compilation of the wire validators (S6 1.3, 5.2). The page's CSP (`script-src 'self'`, no
 * `'unsafe-eval'`) forbids the code generation ajv does when it compiles a schema at run time, so the browser
 * ships validators compiled here, ahead of time, with ajv's standalone code generator: the same options and the
 * same `maxBytes` keyword the run-time compile used, one exported function per wire schema.
 *
 * `generateValidators` is pure; `tools/generate-validators.ts` writes its output to
 * `src/lib/contracts/compiled/validators.{js,d.ts}`, and `validators-codegen.test.ts` fails when the committed
 * files differ from a fresh generation (run `pnpm gen:validators` after `python -m tools.export_contracts`).
 */

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { _ } from "ajv";

import { WIRE_SCHEMAS } from "../src/lib/contracts/generated/schemas.ts";

const HEADER =
  "// Generated by `pnpm gen:validators` (web/tools/validators-codegen.ts) from generated/schemas.ts.\n" +
  "// Do not edit: re-export the contracts, then regenerate; a test fails on any drift.\n";

/** ajv's run-time helper for code-point string length (Pydantic counts code points), inlined: no `require`. */
const UCS2LENGTH = `function ucs2length(str) {
  const len = str.length;
  let length = 0;
  let pos = 0;
  let value;
  while (pos < len) {
    length++;
    value = str.charCodeAt(pos++);
    if (value >= 0xd800 && value <= 0xdbff && pos < len) {
      value = str.charCodeAt(pos);
      if ((value & 0xfc00) === 0xdc00) pos++;
    }
  }
  return length;
}
`;

const UCS2_REQUIRE = 'require("ajv/dist/runtime/ucs2length").default';

/** The export name for a schema stem (`debrief.v1` -> `debrief_v1`). */
export function exportName(stem: string): string {
  return stem.replace(/[^A-Za-z0-9]/g, "_");
}

export interface GeneratedValidators {
  readonly js: string;
  readonly dts: string;
}

export function generateValidators(schemas: Readonly<Record<string, object>> = WIRE_SCHEMAS): GeneratedValidators {
  const ajv = new Ajv2020({ allErrors: true, strict: true, inlineRefs: false, code: { source: true, esm: true } });
  // S2 1, Text size: a string of at most that many UTF-8 bytes.
  ajv.addKeyword({
    keyword: "maxBytes",
    type: "string",
    schemaType: "number",
    code(cxt) {
      const limit = cxt.schema as number;
      cxt.fail(_`new TextEncoder().encode(${cxt.data}).length > ${limit}`);
    },
  });
  const stems = Object.keys(schemas).sort();
  const names = new Map(stems.map((stem) => [exportName(stem), stem]));
  if (names.size !== stems.length) throw new Error("two schema stems map to one export name");
  for (const stem of stems) ajv.addSchema(schemas[stem] as object, stem);
  let code = standaloneCode(ajv, Object.fromEntries(names));
  code = code.split(UCS2_REQUIRE).join("ucs2length");
  if (code.includes("require(")) throw new Error("the generated validators still load a module at run time");
  const table = [...names].map(([name, stem]) => `  ${JSON.stringify(stem)}: ${name},\n`).join("");
  const js =
    `${HEADER}${UCS2LENGTH}${code.replace(/^"use strict";/, "")}\n` +
    `/** The compiled validator of each wire schema, by file stem. */\nexport const WIRE_VALIDATORS = Object.freeze({\n${table}});\n`;
  const dts =
    `${HEADER}import type { ValidateFunction } from "ajv/dist/2020";\n\n` +
    [...names.keys()].map((name) => `export declare const ${name}: ValidateFunction;\n`).join("") +
    "/** The compiled validator of each wire schema, by file stem. */\n" +
    "export declare const WIRE_VALIDATORS: Readonly<Record<string, ValidateFunction>>;\n";
  return { js, dts };
}
