"""Write (or check) the exported contracts and the web's generated contract modules (WP-02; S6 5.2, SG4-05).

    python -m tools.export_contracts            write contracts/*.json and web/src/lib/contracts/generated/*.ts
    python -m tools.export_contracts --check    exit 1 when any of those files differs from a fresh export

`contracts/` gets every schema (`arena_core.contracts.export.contract_files`). The web gets the wire schemas
only: `generated/types.ts` (TypeScript types derived from them) and `generated/schemas.ts` (the same schemas as
modules, compiled by ajv in `src/lib/contracts/validate.ts`). The type generator covers exactly the JSON Schema
subset Pydantic emits for these models and refuses anything else, so a schema it cannot type fails the export
instead of becoming `unknown`.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from arena_core.contracts import export

WEB_GENERATED = Path("web/src/lib/contracts/generated")
CONTRACTS_DIR = Path("contracts")
HEADER = (
    "// Generated by `python -m tools.export_contracts` from the wire schemas in contracts/ (WP-02).\n"
    "// Do not edit: change arena_core.contracts and re-export; a test fails on any drift.\n"
)
_IDENTIFIER = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")
_REF = "#/$defs/"
# Keywords that constrain values without changing the TypeScript type (ajv checks them at run time).
_VALUE_KEYWORDS = frozenset(
    {
        "title",
        "description",
        "default",
        "pattern",
        "minLength",
        "maxLength",
        "minimum",
        "maximum",
        "minItems",
        "maxItems",
        "uniqueItems",
        "maxProperties",
        "additionalProperties",
        "patternProperties",
        "propertyNames",
        "required",
        "properties",
        "items",
        "type",
        "enum",
        "const",
        "anyOf",
        "$ref",
    }
)


class GenerationError(ValueError):
    """A schema outside the subset the type generator understands."""


def _literal(value: object) -> str:
    return json.dumps(value, ensure_ascii=False)


def _key(name: str) -> str:
    return name if _IDENTIFIER.match(name) else _literal(name)


_SCALARS = {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}


def ts_type(schema: Mapping[str, Any], path: str) -> str:
    """The TypeScript type of one schema node."""
    unknown = set(schema) - _VALUE_KEYWORDS
    if unknown:
        msg = f"{path}: unsupported keywords {sorted(unknown)}"
        raise GenerationError(msg)
    if "$ref" in schema:
        return _ref_type(str(schema["$ref"]), path)
    if "const" in schema or "enum" in schema:
        values = schema["enum"] if "enum" in schema else [schema["const"]]
        return " | ".join(_literal(v) for v in values)
    if "anyOf" in schema:
        return " | ".join(ts_type(s, f"{path}.anyOf[{i}]") for i, s in enumerate(schema["anyOf"]))
    kind = schema.get("type")
    if kind == "array":
        if "items" not in schema:
            msg = f"{path}: array without items"
            raise GenerationError(msg)
        return f"readonly ({ts_type(schema['items'], f'{path}.items')})[]"
    if kind == "object":
        return _object_type(schema, path)
    if isinstance(kind, str) and kind in _SCALARS:
        return _SCALARS[kind]
    msg = f"{path}: no type"
    raise GenerationError(msg)


def _ref_type(ref: str, path: str) -> str:
    if not ref.startswith(_REF):
        msg = f"{path}: only local $defs references are supported, not {ref}"
        raise GenerationError(msg)
    return ref[len(_REF) :]


def _object_type(schema: Mapping[str, Any], path: str) -> str:
    if "properties" in schema:
        return "{\n" + _members(schema, path, "  ") + "}"
    names = schema.get("propertyNames", {})
    if "patternProperties" in schema:
        values = list(schema["patternProperties"].values())
        if len(values) != 1:
            msg = f"{path}: one pattern per map"
            raise GenerationError(msg)
        return f"Readonly<Record<string, {ts_type(values[0], f'{path}.patternProperties')}>>"
    value = schema.get("additionalProperties")
    if isinstance(value, Mapping):
        value_type = ts_type(value, f"{path}.additionalProperties")
        if "enum" in names:
            return f"Readonly<Partial<Record<{ts_type(names, f'{path}.propertyNames')}, {value_type}>>>"
        return f"Readonly<Record<string, {value_type}>>"
    msg = f"{path}: free-form object"
    raise GenerationError(msg)


def _members(schema: Mapping[str, Any], path: str, indent: str) -> str:
    required = set(schema.get("required", []))
    lines = []
    for name, sub in schema["properties"].items():
        optional = "" if name in required else "?"
        lines.append(f"{indent}readonly {_key(name)}{optional}: {ts_type(sub, f'{path}.{name}')};\n")
    return "".join(lines)


def _declaration(name: str, schema: Mapping[str, Any], path: str) -> str:
    if schema.get("type") == "object" and "properties" in schema:
        return f"export interface {name} {{\n{_members(schema, path, '  ')}}}\n"
    return f"export type {name} = {ts_type(schema, path)};\n"


def _collect(schemas: Mapping[str, Mapping[str, Any]]) -> tuple[dict[str, Mapping[str, Any]], dict[str, str]]:
    """Every `$defs` entry across the wire schemas (one definition per name) and each file's root type name."""
    defs: dict[str, Mapping[str, Any]] = {}
    roots: dict[str, str] = {}
    for stem, schema in schemas.items():
        for name, sub in schema.get("$defs", {}).items():
            if name in defs and defs[name] != sub:
                msg = f"$defs.{name} differs between wire schemas ({stem})"
                raise GenerationError(msg)
            defs[name] = sub
        roots[stem] = str(schema["title"])
    return defs, roots


def types_module(schemas: Mapping[str, Mapping[str, Any]]) -> str:
    defs, roots = _collect(schemas)
    parts = [HEADER]
    for name in sorted(defs):
        parts.append("\n" + _declaration(name, defs[name], f"$defs.{name}"))
    for stem, title in roots.items():
        if title in defs:
            continue
        root = {k: v for k, v in schemas[stem].items() if k not in {"$schema", "$id", "title", "$defs"}}
        parts.append("\n" + _declaration(title, root, stem))
    parts.append("\n/** The root type of each wire schema, by file stem. */\nexport interface WireTypes {\n")
    parts.extend(f"  readonly {_key(stem)}: {title};\n" for stem, title in roots.items())
    parts.append("}\n")
    return "".join(parts)


def schemas_module(schemas: Mapping[str, Mapping[str, Any]]) -> str:
    body = json.dumps(schemas, indent=2, ensure_ascii=False)
    return (
        HEADER
        + '\nimport type { AnySchemaObject } from "ajv/dist/2020";\n\n'
        + "/** The wire schemas, by file stem (the same JSON as contracts/<stem>.schema.json). */\n"
        + f"export const WIRE_SCHEMAS: Readonly<Record<string, AnySchemaObject>> = {body};\n"
    )


def web_files() -> dict[str, str]:
    """The generated web modules, by path relative to WEB_GENERATED."""
    schemas = {stem: export.schema_of(stem) for stem in export.WIRE}
    return {"types.ts": types_module(schemas), "schemas.ts": schemas_module(schemas)}


def expected_files() -> dict[Path, str]:
    files = {CONTRACTS_DIR / name: text for name, text in export.contract_files().items()}
    files.update({WEB_GENERATED / name: text for name, text in web_files().items()})
    return files


def drift(root: Path) -> list[str]:
    """Generated files that are missing, differ from a fresh export, or are stale leftovers."""
    expected = expected_files()
    problems = [
        str(rel)
        for rel, text in expected.items()
        if not (root / rel).is_file() or (root / rel).read_text(encoding="utf-8") != text
    ]
    for directory, glob in ((CONTRACTS_DIR, "*.json"), (WEB_GENERATED, "*.ts")):
        problems += [
            str(p.relative_to(root))
            for p in sorted((root / directory).glob(glob))
            if p.relative_to(root) not in expected
        ]
    return problems


def write(root: Path) -> None:
    for rel, text in expected_files().items():
        target = root / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path.cwd())
    parser.add_argument("--check", action="store_true", help="fail on drift instead of writing")
    args = parser.parse_args(argv)
    if args.check:
        problems = drift(args.root)
        for problem in problems:
            sys.stderr.write(
                f"contracts: {problem} differs from a fresh export (run python -m tools.export_contracts)\n"
            )
        return 1 if problems else 0
    write(args.root)
    sys.stdout.write(f"contracts: wrote {len(expected_files())} files\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
