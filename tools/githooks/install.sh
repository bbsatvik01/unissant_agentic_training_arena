#!/usr/bin/env bash
# Install the tracked git hooks (`make bootstrap`, S5 10.4). The installed hook is a shim that runs the hook
# tracked in whichever worktree is committing, so every worktree uses its own reviewed copy.
# Fail closed: if the worktree carries this kit (tools/githooks/install.sh) but its hook is missing,
# the commit is blocked. Only a branch that predates the kit entirely is let through, with a note.
# Lifted from TechnoMile tools/githooks/install.sh (ATTRIBUTIONS.md): pre-commit only (TechnoMile's pre-push
# hook runs its hosted cost audit, which arrives here with the hosted variant, WP-33); shim tag renamed.
set -euo pipefail

HOOKS_DIR="$(git rev-parse --git-path hooks)"
HOOKS=(pre-commit)
mkdir -p "$HOOKS_DIR"
for hook in "${HOOKS[@]}"; do
  target="$HOOKS_DIR/$hook"
  if [[ -e "$target" ]] && ! grep -q "arena-githooks-shim" "$target"; then
    echo "install: $target exists and is not ours; move it aside first" >&2
    exit 1
  fi
  cat >"$target" <<SHIM
#!/usr/bin/env bash
# arena-githooks-shim: generated by tools/githooks/install.sh; edit tools/githooks/$hook instead.
set -euo pipefail
top="\$(git rev-parse --show-toplevel)"
tracked="\$top/tools/githooks/$hook"
if [[ -f "\$tracked" ]]; then
  exec /usr/bin/env bash "\$tracked" "\$@"
fi
if [[ -e "\$top/tools/githooks/install.sh" ]]; then
  echo "$hook: tools/githooks/$hook is missing from a tree that carries the hook kit; $hook blocked" >&2
  exit 1
fi
echo "$hook: this branch predates tools/githooks; skipped" >&2
SHIM
  chmod +x "$target"
  echo "install: $hook hook -> tools/githooks/$hook"
done
